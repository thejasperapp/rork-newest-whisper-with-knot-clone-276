import SwiftUI

/// A compact assistant message, not a floating panel over the keyboard.
struct WhisperJasperConversationReply<Details: View>: View {
    let question: String
    let answer: String?
    var isPrivate: Bool = true
    var isSharing: Bool = false
    var error: String? = nil
    var sources: [String] = []
    var onDismiss: (() -> Void)? = nil
    var onShare: (() -> Void)? = nil
    var onRetry: (() -> Void)? = nil
    @ViewBuilder var details: () -> Details
    @Environment(\.colorScheme) private var scheme
    @Environment(\.accessibilityReduceMotion) private var reduceMotion
    @State private var expanded: Bool = false

    var body: some View {
        VStack(alignment: .leading, spacing: 12) {
            if !question.isEmpty {
                HStack {
                    Spacer(minLength: 44)
                    WhisperChatTextBubble(text: "Knot · \(question)", mine: true)
                }
            }
            HStack(alignment: .bottom, spacing: 8) {
                WhisperJasperIntelligenceMark(working: answer == nil && error == nil).frame(width: 30, height: 30)
                    .accessibilityLabel("Knot")
                VStack(alignment: .leading, spacing: 10) {
                    WhisperKnotWordmark()
                    if let answer {
                        WhisperEmberRichText(text: WhisperKnotOutput.clean(answer), onDark: scheme == .dark, baseSize: 16, inkOverride: WhisperTheme.ink(scheme))
                            .textSelection(.enabled)
                        if answer.count > 280 || !sources.isEmpty {
                            Button("Read full answer") { expanded = true }
                                .font(.footnote.weight(.semibold))
                                .frame(minHeight: 44)
                        }
                        details()
                    }
                    if let error {
                        Text(error).font(.footnote).foregroundStyle(.secondary)
                        if let onRetry { Button("Try again", action: onRetry).frame(minHeight: 44) }
                    }
                }
                .padding(.horizontal, 14).padding(.vertical, 10)
                .foregroundStyle(WhisperTheme.ink(scheme))
                .background(WhisperTheme.surface(scheme), in: .rect(cornerRadius: 20))
                .overlay { RoundedRectangle(cornerRadius: 20).strokeBorder(WhisperTheme.hairline(scheme), lineWidth: 0.75) }
                if let onShare, answer != nil {
                    Button(action: onShare) {
                        Group {
                            if isSharing { ProgressView() }
                            else { WhisperRoundedGlyph(kind: .plane, size: 21) }
                        }.frame(width: 44, height: 44)
                    }
                    .buttonStyle(.plain).disabled(isSharing)
                    .accessibilityLabel("Share Knot's answer with this conversation")
                }
                Spacer(minLength: 0)
            }
            if let onDismiss, answer != nil || error != nil {
                Button("Dismiss private answer", action: onDismiss)
                    .font(.caption.weight(.medium))
                    .foregroundStyle(WhisperTheme.muted(scheme))
                    .frame(minHeight: 44).frame(maxWidth: .infinity)
                    .disabled(isSharing)
            }
            Text(isPrivate ? "Only you can see this answer until you share it. Knot can make mistakes." : "Generated by Knot. AI answers can make mistakes.")
                .font(.caption2).foregroundStyle(WhisperTheme.muted(scheme))
                .multilineTextAlignment(.center).frame(maxWidth: .infinity)
        }
        .padding(.vertical, 12)
        .accessibilityElement(children: .contain)
        .sheet(isPresented: $expanded) {
            WhisperEmberPreviewFullSheet(question: question, answer: answer ?? "", sources: sources)
                .presentationDetents([.medium, .large])
                .presentationContentInteraction(.scrolls)
        }
    }
}
