// Deterministic SOURCE-build fingerprint, not the hosting provider's bundle hash.
// Run --write once after code edits; --check is mandatory immediately before deploy.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const target = 'functions/knot-source-build.ts';
const files = ['rork.json', 'scripts/stamp-knot-source-build.ts'];
function walk(directory: string) {
  for (const entry of readdirSync(resolve(root, directory), { withFileTypes: true })) {
    if (entry.name.startsWith('.') || entry.name === 'node_modules') continue;
    const path = directory + '/' + entry.name;
    if (entry.isDirectory()) walk(path);
    else if (entry.isFile() && path !== target && (/\.(?:ts|json|jsonc|toml)$/.test(path) || entry.name === 'bun.lock')) files.push(path);
  }
}
walk('functions');
const hash = createHash('sha256').update('knot_source_build_v1\n');
for (const path of files.sort()) {
  const bytes = readFileSync(resolve(root, path)), name = Buffer.from(path);
  hash.update(String(name.length) + ':').update(name).update(String(bytes.length) + ':').update(bytes);
}
const sha256 = hash.digest('hex');
const content = '// Generated by scripts/stamp-knot-source-build.ts. Source inputs only; excludes this stamp and secrets.\nexport const knotSourceBuildSHA256 = ' + JSON.stringify(sha256) + ';\n';
if (process.argv.includes('--write')) writeFileSync(resolve(root, target), content);
else if (!process.argv.includes('--check')) throw new Error('explicit_write_or_check_required');
if (readFileSync(resolve(root, target), 'utf8') !== content) throw new Error('stale_source_build_stamp');
console.log(JSON.stringify({ sourceBuildSHA256: sha256, inputs: files.length, stamp: relative(root, resolve(root, target)), status: 'verified', scope: 'backend_source_and_build_configuration_not_provider_bundle' }));
